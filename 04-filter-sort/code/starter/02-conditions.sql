-- Στάδιο 2 — Πολλές συνθήκες: AND, OR, BETWEEN, IN και παρενθέσεις.
--
-- Τρέξε κάθε ερώτημα ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL της βάσης game_library, αφού συμπληρώσεις τα κενά (____).
-- ΠΡΩΤΑ πρόβλεψε πόσες γραμμές θα έχει το αποτέλεσμα.

-- Ερώτημα 1 (έτοιμο): αγωνιστικά ΚΑΙ φθηνότερα από 15 €
SELECT title, genre, price
FROM games
WHERE genre = 'Αγωνιστικό' AND price < 15;

-- Ερώτημα 2: είδος «Παζλ» Ή είδος «Αθλητικό»
SELECT title, genre
FROM games
WHERE genre = 'Παζλ' ____ genre = 'Αθλητικό';

-- Ερώτημα 3: τιμή από 5 έως 12 € (και τα δύο όρια περιλαμβάνονται)
SELECT title, price
FROM games
WHERE price ____ 5 ____ 12;

-- Ερώτημα 4: είδος «Παζλ», «Ρόλων» ή «Περιπέτεια», με ένα μόνο έλεγχο
SELECT title, genre
FROM games
WHERE genre ____ ('Παζλ', 'Ρόλων', 'Περιπέτεια');

-- Ερώτημα 5 (έτοιμο): χωρίς παρενθέσεις. Πόσες γραμμές περιμένεις; Πρώτα πρόβλεψε, μετά τρέξ' το.
SELECT title, genre, price
FROM games
WHERE genre = 'Αγωνιστικό' OR genre = 'Αθλητικό' AND price < 15;

-- Ερώτημα 6: θέλουμε (αγωνιστικά Ή αθλητικά) ΚΑΙ φθηνότερα από 15 €. Βάλε τις παρενθέσεις στη σωστή θέση.
SELECT title, genre, price
FROM games
WHERE ____ genre = 'Αγωνιστικό' OR genre = 'Αθλητικό' ____ AND price < 15;
