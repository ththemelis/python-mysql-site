--
-- Πώς το τρέχεις:
--   1. Συμπλήρωσε τα κενά (____) σε έναν επεξεργαστή κειμένου.
--   2. Τρέξε κάθε ερώτημα ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL της βάσης game_library.
--   3. ΠΡΩΤΑ πρόβλεψε πόσες γραμμές θα έχει το αποτέλεσμα. Το phpMyAdmin το γράφει πάνω από τον πίνακα:
--      «Showing rows 0 - 4 (5 total)».

-- Ερώτημα 1 (έτοιμο): τα αγωνιστικά παιχνίδια
SELECT title, price
FROM games
WHERE genre = 'Αγωνιστικό';

-- Ερώτημα 2: τα παιχνίδια που κοστίζουν λιγότερο από 10 €
SELECT title, price
FROM games
WHERE price ____ 10;

-- Ερώτημα 3: τα παιχνίδια που κυκλοφόρησαν το 2022 ή αργότερα
SELECT title, release_year
FROM games
WHERE ____ >= ____;

-- Ερώτημα 4: όλα τα παιχνίδια που ΔΕΝ είναι αγωνιστικά (είδος διαφορετικό από «Αγωνιστικό»)
SELECT title, genre
FROM games
WHERE genre ____ 'Αγωνιστικό';

