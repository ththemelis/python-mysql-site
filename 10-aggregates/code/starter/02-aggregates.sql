-- Στάδιο 1 — Συγκεντρωτικά αποτελέσματα: COUNT, SUM, AVG, MIN, MAX.
--
-- Πριν αρχίσεις: τρέξε το 01-start-state.sql (καρτέλα Import), ώστε ο games να έχει 30 γραμμές.
--
-- Πώς το τρέχεις:
--   1. Συμπλήρωσε τα κενά (____) σε έναν επεξεργαστή κειμένου.
--   2. Τρέξε κάθε εντολή ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL της βάσης game_library.
--   3. ΠΡΩΤΑ πρόβλεψε το αποτέλεσμα. Κάθε εντολή δίνει ΜΙΑ γραμμή: ένα αποτέλεσμα για όλον τον πίνακα.

-- Ερώτημα 1 (έτοιμο): πόσα παιχνίδια έχει η βιβλιοθήκη;
SELECT COUNT(*)
FROM games;

-- Ερώτημα 2: πόσο κοστίζουν όλα μαζί (άθροισμα) και ποια είναι η μέση τιμή;
SELECT ____(price), AVG(price)
FROM games;

-- Ερώτημα 3: η φθηνότερη τιμή και η ακριβότερη τιμή
SELECT ____(price), MAX(price)
FROM games;

-- Ερώτημα 4: ψευδώνυμα (AS) και στρογγυλοποίηση της μέσης τιμής σε δύο δεκαδικά
SELECT COUNT(*) AS games, ROUND(AVG(price), ____) AS average
FROM games;

-- Ερώτημα 5 (έτοιμο): συγκεντρωτικά ΜΟΝΟ για τα αγωνιστικά. Το WHERE φιλτράρει τις γραμμές ΠΡΙΝ τον υπολογισμό
SELECT COUNT(*), AVG(price)
FROM games
WHERE genre = 'Αγωνιστικό';

-- Ερώτημα 6: το παλαιότερο και το νεότερο έτος κυκλοφορίας
SELECT MIN(release_year), ____(release_year)
FROM games;

-- Ερώτημα 7: πόσα ΔΙΑΦΟΡΕΤΙΚΑ είδη υπάρχουν; (το DISTINCT του Μαθήματος 2, μέσα στο COUNT)
SELECT COUNT(____ genre)
FROM games;

-- Ερώτημα 8 (έτοιμο): το COUNT(*) μετρά ΓΡΑΜΜΕΣ, το COUNT(στήλη) μετρά μόνο τις τιμές που ΔΕΝ είναι NULL
-- (θυμήσου ότι η περιγραφή description είναι NULL στα περισσότερα παιχνίδια). Πρόβλεψε τα δύο αποτελέσματα
SELECT COUNT(*), COUNT(description)
FROM games;

-- Ερώτημα 9 (έτοιμο): τι δίνουν όταν δεν υπάρχει ΚΑΜΙΑ γραμμή που να ταιριάζει;
SELECT COUNT(*), SUM(price), AVG(price)
FROM games
WHERE genre = 'Δεν υπάρχει';

-- Ερώτημα 10 (έτοιμο): η MAX δίνει μια ΤΙΜΗ, όχι μια ΓΡΑΜΜΗ. Για να βρεις ποιο παιχνίδι είναι το ακριβότερο,
-- χρησιμοποίησε ORDER BY και LIMIT (Μάθημα 4)
SELECT title, price
FROM games
ORDER BY price DESC
LIMIT 1;
