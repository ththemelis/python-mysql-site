-- Στάδιο 1 — Ημερομηνίες και ώρες στη SQL: συναρτήσεις και συγκρίσεις.
--
-- Οι εντολές αυτού του αρχείου ΔΕΝ χρειάζονται πίνακα: δουλεύουν με ημερομηνίες που γράφεις εσύ.
--
-- Πώς το τρέχεις:
--   1. Συμπλήρωσε τα κενά (____) σε έναν επεξεργαστή κειμένου.
--   2. Τρέξε κάθε εντολή ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL της βάσης game_library.
--   3. ΠΡΩΤΑ πρόβλεψε το αποτέλεσμα. Οι ημερομηνίες γράφονται σε εισαγωγικά, στη μορφή ΕΕΕΕ-ΜΜ-ΗΗ.

-- Ερώτημα 1 (έτοιμο): τι ημερομηνία και ώρα είναι στη βάση τώρα;
SELECT NOW(), CURDATE(), CURTIME();

-- Ερώτημα 2: τα μέρη μιας ημερομηνίας (η 15 Σεπτεμβρίου 2026 γράφεται '2026-09-15')
SELECT YEAR('2026-09-15'), ____('2026-09-15'), DAY('2026-09-15');

-- Ερώτημα 3: η ημερομηνία στην ελληνική μορφή ΗΗ/ΜΜ/ΕΕΕΕ (το %Y είναι το έτος με τέσσερα ψηφία)
SELECT DATE_FORMAT('2026-09-15', '%d/%m/____');

-- Ερώτημα 4: πόσες ημέρες απέχουν δύο ημερομηνίες; (ΠΡΩΤΑ η μεταγενέστερη, ΜΕΤΑ η προηγούμενη)
SELECT ____('2026-12-25', '2026-09-15');

-- Ερώτημα 5: ποια ημερομηνία είναι 30 ημέρες μετά τις 15 Σεπτεμβρίου;
SELECT '2026-09-15' + INTERVAL ____ DAY;

-- Ερώτημα 6: οι ημερομηνίες ΕΕΕΕ-ΜΜ-ΗΗ συγκρίνονται σωστά. Η 5 Σεπτεμβρίου είναι πριν από την 1 Οκτωβρίου;
-- (το αποτέλεσμα 1 σημαίνει «αληθές», το 0 «ψευδές»)
SELECT '2026-09-05' ____ '2026-10-01';

-- Ερώτημα 7 (έτοιμο): ελληνικά ονόματα ημερών και μηνών
SET lc_time_names = 'el_GR';
SELECT DAYNAME('2026-09-15'), MONTHNAME('2026-09-15');

-- Ερώτημα 8 (έτοιμο): μια ΑΚΥΡΗ ημερομηνία. Η 30 Φεβρουαρίου δεν υπάρχει. Τι αποτέλεσμα δίνει;
SELECT DATE('2026-02-30');

-- Ερώτημα 9 (έτοιμο): ημερομηνία ΚΑΙ ώρα (τύπος DATETIME): '2026-09-15 14:30:00'. Το %H είναι η ώρα, το %i τα λεπτά
SELECT DATE_FORMAT('2026-09-15 14:30:00', '%d/%m/%Y %H:%i');

-- Ερώτημα 10: πόσα λεπτά περνούν από τις 8:00 μέχρι τις 14:30; (η TIMESTAMPDIFF παίρνει πρώτα τη μονάδα)
SELECT TIMESTAMPDIFF(____, '2026-09-15 08:00:00', '2026-09-15 14:30:00');
