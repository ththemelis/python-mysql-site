-- Στάδιο 1 — Λογαριασμοί και δικαιώματα.
--
-- Τρέχεις αυτό το αρχείο ΩΣ root (στο phpMyAdmin είσαι ήδη root): μόνο ο διαχειριστής φτιάχνει λογαριασμούς. Οι λογαριασμοί ανήκουν
-- στον ΕΞΥΠΗΡΕΤΗ, όχι στη βάση game_library· δεν τους σβήνει το 01-start-state.sql.
--
-- Πώς το τρέχεις:
--   1. Συμπλήρωσε τα κενά (____) σε έναν επεξεργαστή κειμένου.
--   2. Τρέξε κάθε εντολή ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL (δεν χρειάζεται να είναι επιλεγμένη κάποια βάση), με τη σειρά.
--   3. ΠΡΩΤΑ πρόβλεψε τι θα γίνει: τι θα δείξει το SHOW GRANTS;
--
-- Οι κωδικοί εδώ είναι κωδικοί ΜΑΘΗΜΑΤΟΣ και τους ξέρουν όλοι. Σε πραγματικό σύστημα ο κωδικός είναι μυστικός.

-- Βήμα 1 (έτοιμο): ποιος είμαι και ποιοι λογαριασμοί υπάρχουν ήδη;
SELECT CURRENT_USER();
SELECT user, host FROM mysql.user;

-- Βήμα 2 (έτοιμο): καθαρισμός, ώστε να μπορείς να ξανατρέξεις το αρχείο όσες φορές θέλεις
DROP USER IF EXISTS 'game_app'@'localhost';
DROP USER IF EXISTS 'game_reader'@'localhost';

-- Βήμα 3: ο λογαριασμός της εφαρμογής, ΜΕ κωδικό. Το 'localhost' σημαίνει ότι μπαίνει μόνο από αυτόν τον υπολογιστή
CREATE ____ 'game_app'@'localhost' IDENTIFIED BY 'app-pass-2026';

-- Βήμα 4: ο λογαριασμός των αναφορών, επίσης με κωδικό
CREATE USER 'game_reader'@'localhost' IDENTIFIED ____ 'reader-pass-2026';

-- Βήμα 5: η εφαρμογή διαβάζει και αλλάζει δεδομένα: τέσσερα δικαιώματα, και μόνο στους πίνακες της game_library
-- (ΟΧΙ CREATE, ALTER ή DROP: δεν αλλάζει τη δομή της βάσης)
GRANT SELECT, INSERT, UPDATE, ____ ON game_library.* TO 'game_app'@'localhost';

-- Βήμα 6: οι αναφορές μόνο διαβάζουν: ένα δικαίωμα
GRANT ____ ON game_library.* TO 'game_reader'@'localhost';

-- Βήμα 7: τι δικαιώματα έχει ο καθένας; Πόσες γραμμές δείχνει το καθένα;
SHOW GRANTS FOR 'game_app'@'localhost';
SHOW ____ FOR 'game_reader'@'localhost';
