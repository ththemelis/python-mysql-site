-- 2. ΔΗΜΙΟΥΡΓΙΑ. Ένα CREATE TABLE για κάθε πίνακα, με την ανάποδη σειρά: ΠΡΩΤΑ οι «γονείς», ΜΕΤΑ τα «παιδιά». Πρότυπο (σβήσε τα σχόλια και συμπλήρωσε):
--
-- CREATE TABLE όνομα_πίνακα (
--   id         INT           NOT NULL AUTO_INCREMENT,
--   όνομα      VARCHAR(60)   NOT NULL,
--   τιμή       DECIMAL(5,2)  NOT NULL,
--   πότε       DATETIME      NOT NULL DEFAULT (NOW()),
--   γονέας_id  INT           NOT NULL,
--   PRIMARY KEY (id),
--   UNIQUE (όνομα),
--   CONSTRAINT chk_όνομαπίνακα_τιμή CHECK (τιμή > 0),
--   CONSTRAINT fk_όνομαπίνακα_γονέας FOREIGN KEY (γονέας_id) REFERENCES γονέας (id)
-- );
--
-- ΠΙΝΑΚΑΣ ΣΥΝΔΕΣΗΣ (σχέση πολλά-προς-πολλά): ΧΩΡΙΣ δικό του id. Δύο στήλες που είναι ΚΑΙ τα δύο ξένα κλειδιά ΚΑΙ μαζί το πρωτεύον κλειδί, και όσες
-- επιπλέον στήλες χρειάζεται η σχέση (π.χ. ποσότητα):
--
-- CREATE TABLE πίνακας_σύνδεσης (
--   α_id       INT  NOT NULL,
--   β_id       INT  NOT NULL,
--   ποσότητα   INT  NOT NULL DEFAULT 1,
--   PRIMARY KEY (α_id, β_id),
--   CONSTRAINT fk_σύνδεσης_α FOREIGN KEY (α_id) REFERENCES α_πίνακας (id),
--   CONSTRAINT fk_σύνδεσης_β FOREIGN KEY (β_id) REFERENCES β_πίνακας (id)
-- );
--
-- Λίστα ελέγχου για ΚΑΘΕ πίνακα: ✔ πρωτεύον κλειδί  ✔ NOT NULL όπου δεν επιτρέπεται το «κενό»  ✔ UNIQUE όπου δεν επιτρέπεται η επανάληψη
--                               ✔ CHECK όπου υπάρχει όριο τιμών  ✔ DEFAULT όπου υπάρχει «συνηθισμένη» τιμή  ✔ ξένο κλειδί για κάθε σχέση ένα-προς-πολλά
--
-- Ονόματα: πεζά λατινικά με κάτω παύλα (customers, order_items). Πίνακες στον πληθυντικό, στήλες στον ενικό, ξένο κλειδί = ενικός_γονέα + _id (customer_id).

