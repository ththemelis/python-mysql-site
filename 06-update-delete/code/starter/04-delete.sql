WHERE id = ____;

-- Ερώτημα 3 (έτοιμο): ποια id έχουν τα τρία «Mini Golf»;
SELECT id, title
FROM games
WHERE title = 'Mini Golf';

-- Ερώτημα 4: κράτα το πρώτο (id 11) και σβήσε τα άλλα δύο με ΜΙΑ εντολή
DELETE FROM games
WHERE id ____ (12, 13);

-- Ερώτημα 5: πόσα παιχνίδια έμειναν στον πίνακα;
