-- Πώς το τρέχεις:
--   1. Συμπλήρωσε τα κενά (____) σε έναν επεξεργαστή κειμένου.
--   2. Τρέξε κάθε εντολή ΞΕΧΩΡΙΣΤΑ στην καρτέλα SQL της βάσης game_library.
--   3. ΠΡΩΤΑ πρόβλεψε πόσες γραμμές θα σβηστούν. Μετά την DELETE το phpMyAdmin γράφει «N rows deleted».
--   4. Η DELETE δεν έχει «Αναίρεση». Πριν από κάθε DELETE κάνε SELECT με το ίδιο WHERE. Το phpMyAdmin θα ρωτήσει
--      «Do you really want to execute…?»: διάβασε την εντολή και πάτα OK.

-- Ερώτημα 1 (έτοιμο): ΔΕΣ πρώτα τη γραμμή που θα σβήσεις: το δοκιμαστικό παιχνίδι με id 17
SELECT *
FROM games
WHERE id = 17;

-- Ερώτημα 2: σβήσε το δοκιμαστικό παιχνίδι
