-- Ερώτημα 4 (έτοιμο): ΘΑ ΔΩΣΕΙ ΣΦΑΛΜΑ. Κάθε ερώτημα που διαβάζει τη στήλη genre σπάει: το ίδιο θα γίνει στα
-- προγράμματα των Μαθημάτων 7–10
SELECT id, title, genre
FROM games;

-- Ερώτημα 5: το όνομα του είδους έρχεται πια ΜΟΝΟ με JOIN
SELECT g.id, g.title, ____.name AS genre_name
FROM games AS g
JOIN genres AS ge ON g.genre_id = ge.id
ORDER BY g.id
LIMIT 5;

