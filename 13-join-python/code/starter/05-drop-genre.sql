-- Ερώτημα 1 (έτοιμο): έλεγχος συνέπειας. Πριν σβήσεις ένα κείμενο, βεβαιώσου ότι δεν χάνεις πληροφορία: διαφωνεί η
-- στήλη genre με το όνομα του είδους που δείχνει η genre_id; Δεν πρέπει να βγει καμία γραμμή
SELECT g.id, g.title, g.genre, ge.name
FROM games AS g
JOIN genres AS ge ON g.genre_id = ge.id
WHERE g.genre <> ge.name;

-- Ερώτημα 2: σβήσε τη στήλη genre. ΠΡΟΣΟΧΗ: η εντολή σβήνει τη στήλη ΜΑΖΙ ΜΕ τα δεδομένα της, χωρίς επιβεβαίωση
